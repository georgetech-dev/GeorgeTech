create table if not exists public.contact_requests (
  id bigint generated by default as identity primary key,
  reference text not null unique,
  created_at timestamptz not null default now(),
  name text not null,
  business text,
  email text,
  phone text,
  preferred_contact text not null,
  preferred_time text,
  reason text not null,
  message text not null,
  privacy_acknowledged boolean not null default false,
  status text not null default 'new',
  constraint contact_requests_preferred_contact_check
    check (preferred_contact in ('email', 'phone', 'either')),
  constraint contact_requests_status_check
    check (status in ('new', 'contacted', 'closed'))
);

alter table public.contact_requests enable row level security;

revoke all on table public.contact_requests from anon, authenticated;
grant insert on table public.contact_requests to anon, authenticated;
grant usage, select on sequence public.contact_requests_id_seq to anon, authenticated;

drop policy if exists "Public can submit contact requests" on public.contact_requests;
create policy "Public can submit contact requests"
on public.contact_requests
for insert
to anon, authenticated
with check (
  char_length(btrim(name)) between 1 and 120
  and (business is null or char_length(btrim(business)) <= 160)
  and (email is null or char_length(btrim(email)) <= 254)
  and (phone is null or char_length(btrim(phone)) <= 40)
  and (
    (preferred_contact = 'email' and email is not null and char_length(btrim(email)) > 3)
    or (preferred_contact = 'phone' and phone is not null and char_length(btrim(phone)) > 5)
    or (preferred_contact = 'either' and (
      (email is not null and char_length(btrim(email)) > 3)
      or (phone is not null and char_length(btrim(phone)) > 5)
    ))
  )
  and char_length(btrim(reason)) between 1 and 160
  and char_length(btrim(message)) between 1 and 4000
  and privacy_acknowledged is true
  and status = 'new'
);

comment on table public.contact_requests is
  'Public callback and enquiry requests submitted through georgetech.uk.';
